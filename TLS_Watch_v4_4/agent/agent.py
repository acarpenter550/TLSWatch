@app.get("/api/state")
def public_state():
    with lock:
        c = dict(config)
        result = dict(state)
    result.update({"configured": bool(c.get("token")), "agent_name": c.get("agent_name"),
                   "primary_url": c.get("primary_url")})
    return jsonify(result)


@app.post("/api/pair")
def pair():
    body = request.get_json(silent=True) or {}
    if not isinstance(body, dict):
        return jsonify({"error": "Invalid configuration"}), 400
    try:
        allow = body.get("allow_http") is True
        server = primary_url(str(body.get("primary_url", "")), allow)
        code = body.get("enrollment_code", "")
        ca = body.get("ca_pem", "")
        if not isinstance(code, str) or not 35 <= len(code) <= 160:
            raise ValueError("Paste the complete enrollment code")
        if not isinstance(ca, str) or len(ca) > 20000:
            raise ValueError("Custom CA certificate is too large")
        pending = {"primary_url": server, "ca_pem": ca, "allow_http": allow}
        response = primary_call(pending, "/agent/v1/enroll", {"enrollment_code": code})
        token = response.get("agent_token")
        if not isinstance(token, str) or not token.startswith("tlsw-agent-"):
            raise ValueError("Primary enrollment response was invalid")
        pending.update({"token": token,"agent_id": response["agent_id"],
                        "agent_name": response["agent_name"]})
        save_config(pending)
        with lock:
            state["last_error"] = None
        return jsonify({"ok": True})
    except Exception as exc:
        return jsonify({"error": f"{type(exc).__name__}: {exc}"[:600]}), 400


@app.post("/api/disconnect")
def disconnect():
    with lock:
        config.clear()
    try:
        CONFIG_FILE.unlink(missing_ok=True)
    except OSError as exc:
        return jsonify({"error": str(exc)}), 500
    return jsonify({"ok": True})


