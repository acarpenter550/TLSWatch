def stamp() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")


def load_config() -> None:
    global config
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    if CONFIG_FILE.exists():
        with lock:
            config = json.loads(CONFIG_FILE.read_text(encoding="utf-8"))


def save_config(new: dict) -> None:
    global config
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    temporary = CONFIG_FILE.with_suffix(".tmp")
    temporary.write_text(json.dumps(new, indent=2), encoding="utf-8")
    try:
        os.chmod(temporary, 0o600)
    except OSError:
        pass
    temporary.replace(CONFIG_FILE)
    with lock:
        config = dict(new)


def primary_url(raw: str, allow_http: bool) -> str:
    value = raw.strip().rstrip("/")
    parsed = urlsplit(value)
    if (parsed.scheme != "https" and not (parsed.scheme == "http" and allow_http)) or not parsed.hostname:
        raise ValueError("Use an HTTPS primary URL, or explicitly allow HTTP for trusted testing")
    if parsed.username or parsed.password or parsed.query or parsed.fragment or parsed.path not in ("", "/"):
        raise ValueError("Primary URL must be an origin (scheme + host + optional port)")
    if parsed.port is not None and not 1 <= parsed.port <= 65535:
        raise ValueError("Invalid primary port")
    return value


def make_context(settings: dict):
    context = ssl.create_default_context()
    custom_ca = settings.get("ca_pem", "")
    if custom_ca:
        context.load_verify_locations(cadata=custom_ca)
    return context


class RejectRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        raise RuntimeError("Primary redirected the request; refusing to forward agent credentials")


def primary_call(settings: dict, path: str, data: dict) -> dict:
    raw = json.dumps(data).encode("utf-8")
    req = urllib.request.Request(settings["primary_url"] + path, raw,
              {"Content-Type": "application/json", "User-Agent": "TLSWatch-Agent/4.4"}, method="POST")
    if path != "/agent/v1/enroll":
        req.add_header("Authorization", "Bearer " + settings["token"])
    try:
        opener = urllib.request.build_opener(RejectRedirect(),
                  urllib.request.HTTPSHandler(context=make_context(settings)))
        with opener.open(req, timeout=18) as response:
            result = response.read(100_000)
            return json.loads(result)
    except urllib.error.HTTPError as exc:
        detail = exc.read(2000).decode("utf-8", "replace")
        raise RuntimeError(f"Primary returned HTTP {exc.code}: {detail[:400]}") from exc


def tls_handshake(host: str, dest: tuple, verify: bool):
    family, address = dest
    ctx = ssl.create_default_context() if verify else ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    if not verify:
        ctx.check_hostname = False
        ctx.verify_mode = ssl.CERT_NONE
    with socket.socket(family, socket.SOCK_STREAM) as sock:
        sock.settimeout(TLS_TIMEOUT)
        sock.connect(address)
        with ctx.wrap_socket(sock, server_hostname=host) as channel:
            return None if verify else channel.getpeercert(binary_form=True)


def check_certificate(host: str, port: int) -> dict:
    # Resolve/connect from the remote agent's LAN. No HTTP request or page download.
    addresses = socket.getaddrinfo(host, port, type=socket.SOCK_STREAM)
    if not addresses:
        raise OSError("Hostname has no resolved addresses")
    last_error = None
    der, chosen = None, None
    for family, _, _, _, sockaddr in addresses:
        try:
            der = tls_handshake(host, (family, sockaddr), False)
            if der:
                chosen = (family, sockaddr)
                break
        except (OSError, ssl.SSLError) as exc:
            last_error = exc
    if der is None or chosen is None:
        raise OSError(str(last_error or "Server did not present a certificate"))
    if len(der) > 30_000:
        raise ValueError("Certificate exceeds maximum supported length")
    pem = ssl.DER_cert_to_PEM_cert(der)
    verify_error = None
    verified = True
    try:
        tls_handshake(host, chosen, True)
    except (OSError, ssl.SSLError) as exc:
        verified = False
        verify_error = str(exc)[:600]
    return {"success": True, "certificate_pem": pem, "tls_verified": verified,
            "verify_error": verify_error}


def run_task(settings: dict, task: dict):
    with lock:
        state["running"] += 1
    try:
        try:
            report = check_certificate(task["hostname"], int(task["port"]))
        except Exception as exc:
            report = {"success": False, "error": (f"{type(exc).__name__}: {exc}")[:800]}
        result = {"site_id": task["site_id"], "lease": task["lease"], **report}
        primary_call(settings, "/agent/v1/result", result)
        with lock:
            state["last_result"] = {"site": task["url"], "success": report["success"], "at": stamp()}
            state["checks"] += 1
            state["last_error"] = None
    except Exception as exc:
        with lock:
            state["last_error"] = f"Could not deliver result for {task.get('url','site')}: {exc}"[:500]
    finally:
        with lock:
            state["running"] -= 1


def polling_loop():
    while not stop_event.is_set():
        with lock:
            current = dict(config)
            available = max(0, WORKERS - state["running"])
        if current.get("token"):
            try:
                payload = primary_call(current, "/agent/v1/poll", {"version": VERSION, "capacity": available})
                with lock:
                    state["last_contact"] = stamp()
                    state["last_error"] = None
                for task in payload.get("tasks", []):
                    threads.submit(run_task, current, task)
            except Exception as exc:
                with lock:
                    state["last_error"] = str(exc)[:500]
        stop_event.wait(POLL_SECONDS)


@app.before_request
def protect_setup():
    # Docker Compose maps the UI to the HOST's loopback only (127.0.0.1:8899).
    # For other deployments, protect the UI behind an authenticated proxy.
    if request.method == "POST":
        origin = request.headers.get("Origin", "")
        if origin:
            parsed = urlsplit(origin)
            if parsed.scheme not in ("http", "https") or parsed.netloc != request.host:
                return jsonify({"error": "Invalid origin"}), 403


