VERSION = "4.4.0"
DATA_DIR = Path(os.environ.get("AGENT_DATA_DIR", "/data"))
CONFIG_FILE = DATA_DIR / "agent.json"
PORT = int(os.environ.get("AGENT_UI_PORT", "8899"))
POLL_SECONDS = max(5, min(60, int(os.environ.get("POLL_SECONDS", "15"))))
TLS_TIMEOUT = max(3, min(30, int(os.environ.get("TLS_TIMEOUT_SECONDS", "8"))))
WORKERS = max(1, min(4, int(os.environ.get("AGENT_WORKERS", "3"))))

